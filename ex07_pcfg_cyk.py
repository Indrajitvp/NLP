"""Ex 7: PCFG (CNF) - inside probability and Viterbi parse via CYK."""
from collections import defaultdict
from nltk import Tree

lexical = {("Det", "the"): 1.0, ("N", "cat"): 0.5, ("N", "dog"): 0.5,
           ("V", "chased"): 1.0, ("P", "with"): 1.0}
binary = {("S", "NP", "VP"): 1.0,
          ("NP", "Det", "N"): 0.7, ("NP", "NP", "PP"): 0.3,
          ("VP", "V", "NP"): 0.7, ("VP", "VP", "PP"): 0.3,
          ("PP", "P", "NP"): 1.0}
NTS = sorted({a for a, _ in lexical} | {a for a, _, _ in binary})


def cyk(words):
    n = len(words)
    inside = defaultdict(float)   # (i, j, A) -> sum over all parses
    best = defaultdict(float)     # (i, j, A) -> max over parses
    back = {}
    for i, w in enumerate(words):
        for A in NTS:
            p = lexical.get((A, w), 0.0)
            if p:
                inside[i, i, A] = best[i, i, A] = p
    for span in range(2, n + 1):
        for i in range(n - span + 1):
            j = i + span - 1
            for m in range(i, j):
                for (A, B, C), p in binary.items():
                    l, r = inside[i, m, B], inside[m + 1, j, C]
                    if l and r:
                        inside[i, j, A] += p * l * r
                        cand = p * best[i, m, B] * best[m + 1, j, C]
                        if cand > best[i, j, A]:
                            best[i, j, A] = cand
                            back[i, j, A] = (m, B, C)
    return inside, best, back


def build(back, words, i, j, A):
    if i == j:
        return Tree(A, [words[i]])
    m, B, C = back[i, j, A]
    return Tree(A, [build(back, words, i, m, B), build(back, words, m + 1, j, C)])


def run(sentence):
    words = sentence.lower().split()
    n = len(words)
    inside, best, back = cyk(words)
    print(f"\nSentence: {sentence}")
    for A in NTS:
        print(f"Inside probability of {A}: {inside[0, n - 1, A]}")
    print(f"P(sentence) = inside(S) = {inside[0, n - 1, 'S']:.6f}")
    if best[0, n - 1, "S"]:
        print(f"Best parse probability = {best[0, n - 1, 'S']:.6f}")
        build(back, words, 0, n - 1, "S").pretty_print()
    else:
        print("Sentence not generated by grammar")


run("The cat chased the dog")
run("The cat chased the dog with the cat")   # ambiguous: inside = sum of both parses
